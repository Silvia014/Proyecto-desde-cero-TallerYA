-- FastAPI connects directly. This schema is not exposed through PostgREST.
CREATE SCHEMA IF NOT EXISTS tallerya;
REVOKE ALL ON SCHEMA tallerya FROM PUBLIC;
SET search_path = tallerya, pg_catalog;

CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT UNIQUE NOT NULL,
 phone TEXT NOT NULL, password TEXT NOT NULL, locale TEXT NOT NULL,
 notices INTEGER NOT NULL, privacy TEXT NOT NULL, accepted BIGINT NOT NULL,
 role TEXT NOT NULL DEFAULT 'student', version INTEGER NOT NULL DEFAULT 0,
 deleted INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS one_owner ON users(role) WHERE role='owner';
CREATE TABLE IF NOT EXISTS workshops (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, es TEXT NOT NULL, en TEXT NOT NULL,
 starts BIGINT NOT NULL, minutes INTEGER NOT NULL, price BIGINT NOT NULL,
 currency TEXT NOT NULL, capacity INTEGER NOT NULL, published INTEGER NOT NULL,
 teacher BIGINT REFERENCES users(id), venue TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS bookings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workshop BIGINT NOT NULL REFERENCES workshops(id),
 "user" BIGINT NOT NULL REFERENCES users(id), status TEXT NOT NULL,
 price BIGINT NOT NULL, currency TEXT NOT NULL, paid BIGINT NOT NULL DEFAULT 0,
 refund INTEGER NOT NULL DEFAULT 0, refunded BIGINT NOT NULL DEFAULT 0,
 deadline BIGINT, payment_url TEXT, sent BIGINT, certificate BYTEA
);
CREATE UNIQUE INDEX IF NOT EXISTS one_place ON bookings(workshop,"user")
 WHERE status IN ('hold','payment','confirmed');
CREATE TABLE IF NOT EXISTS interests (
 workshop BIGINT REFERENCES workshops(id), "user" BIGINT REFERENCES users(id),
 PRIMARY KEY(workshop,"user")
);
CREATE TABLE IF NOT EXISTS outbox (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dedupe TEXT UNIQUE NOT NULL, recipient BIGINT NOT NULL REFERENCES users(id),
 kind TEXT NOT NULL, workshop BIGINT NOT NULL, locale TEXT NOT NULL,
 subject TEXT NOT NULL, body TEXT NOT NULL, sent BIGINT
);
CREATE TABLE IF NOT EXISTS demo_seed (marker INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, locale TEXT NOT NULL, happened BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS workshops_catalog ON workshops(starts) WHERE published=1;
CREATE INDEX IF NOT EXISTS workshops_teacher ON workshops(teacher,starts);
CREATE INDEX IF NOT EXISTS bookings_member ON bookings("user",id);
CREATE INDEX IF NOT EXISTS bookings_edition ON bookings(workshop,status);
CREATE INDEX IF NOT EXISTS bookings_payment_deadline ON bookings(deadline) WHERE status='payment';
CREATE INDEX IF NOT EXISTS outbox_pending ON outbox(id) WHERE sent IS NULL;
CREATE INDEX IF NOT EXISTS events_retention ON events(happened);

ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE workshops ENABLE ROW LEVEL SECURITY;
ALTER TABLE bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE interests ENABLE ROW LEVEL SECURITY;
ALTER TABLE events ENABLE ROW LEVEL SECURITY;
ALTER TABLE outbox ENABLE ROW LEVEL SECURITY;
ALTER TABLE demo_seed ENABLE ROW LEVEL SECURITY;

RESET search_path;
